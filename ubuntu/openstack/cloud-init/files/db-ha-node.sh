#!/usr/bin/env bash
# First-boot setup of one node of the database HA group (docs/db-ha-patroni.md). Installed by cloud-init as /usr/local/sbin/db-ha-node and run once.
#
#   role "database": etcd member + PostgreSQL 16 under Patroni      (db1, db2)
#   role "witness":  etcd member only, the third voter              (db-witness)
#
# Input, written by cloud-init (Terraform renders it): /etc/db-ha/node.env (ROLE, MEMBERS="name=ip,...") and /etc/db-ha/secrets (0600).
# The same script builds a brand-new group and replaces one lost machine of a running group; it decides by looking at what answers:
#   * etcd:    a healthy member answers  -> remove any stale entry for this name/IP, `member add`, start as "existing";
#              nobody answers            -> start as part of a NEW cluster made of all MEMBERS (the other two do the same when they boot).
#   * Patroni: starts with an empty data directory. If the cluster already has a leader, it copies the leader (pg_basebackup) and follows it;
#              if there is no cluster yet, one of the two initialises an empty database and the other copies it.
# Facts learned on the live pair that are encoded here (details: header of scripts/db-ha-patroni.sh):
#   * Patroni overwrites /etc/postgresql/16/main/postgresql.conf with a stub, so the packaged file is copied to postgresql.base.conf first (custom_conf).
#   * Patroni logs in to Postgres over loopback TCP with a password; pg_hba.conf is generated by Patroni from the list below, so it is identical on both.
#   * postgresql@16-main is masked: Patroni, not systemd, starts and stops PostgreSQL.
# Re-running does nothing once /var/lib/db-ha-node.done exists. Log: /var/log/db-ha-node.log.
set -euo pipefail
exec > >(tee -a /var/log/db-ha-node.log) 2>&1

[ ! -e /var/lib/db-ha-node.done ] || { echo "already done"; exit 0; }
# shellcheck disable=SC1091
. /etc/db-ha/node.env
# shellcheck disable=SC1091
. /etc/db-ha/secrets

SCOPE=finance-db
PGV=16
ME=$(hostname -s)
export ETCDCTL_API=3

member_ip() { echo "$MEMBERS" | tr ',' '\n' | awk -F= -v n="$1" '$1==n{print $2}'; }
MYIP=$(member_ip "$ME")
[ -n "$MYIP" ] || { echo "$ME is not in MEMBERS=$MEMBERS" >&2; exit 1; }
OTHERS=$(echo "$MEMBERS" | tr ',' '\n' | awk -F= -v n="$ME" '$1!=n{print $2}')
ALL_IPS=$(echo "$MEMBERS" | tr ',' '\n' | awk -F= '{print $2}' | paste -sd, -)
echo "== $(date -Is) $ME ($ROLE) $MYIP, group: $MEMBERS"

apt_install() {
  local i
  for i in 1 2 3 4 5; do
    DEBIAN_FRONTEND=noninteractive apt-get install -y -qq -o DPkg::Lock::Timeout=120 "$@" && return 0
    sleep 20
  done
  return 1
}

# ---------------------------------------------------------------------------------------------------- packages
PKGS="etcd-server etcd-client nftables jq curl dnsutils"
[ "$ROLE" != database ] || PKGS="$PKGS postgresql-$PGV patroni python3-etcd3 python3-psycopg2 nfs-common"
apt_install $PKGS
systemctl stop etcd 2>/dev/null || true
rm -rf /var/lib/etcd/default            # the package starts a single-node etcd of its own; it must not exist
if [ "$ROLE" = database ]; then
  systemctl stop postgresql 2>/dev/null || true
  systemctl stop "postgresql@$PGV-main" 2>/dev/null || true
fi

# ---------------------------------------------------------------------------------------------------- firewall
# etcd has no TLS and no login: only the group's members may reach it; Patroni's REST port only the private subnet.
cat > /etc/nftables-etcd.conf <<NFT
# managed by cloud-init (db-ha-node)
table inet etcd_guard
delete table inet etcd_guard
table inet etcd_guard {
  chain input {
    type filter hook input priority -10; policy accept;
    tcp dport { 2379, 2380 } ip saddr != { 127.0.0.1, $ALL_IPS } drop
    tcp dport 8008 ip saddr != { 127.0.0.1, 10.0.1.0/24 } drop
  }
}
NFT
grep -q "nftables-etcd.conf" /etc/nftables.conf || echo 'include "/etc/nftables-etcd.conf"' >> /etc/nftables.conf
nft -f /etc/nftables-etcd.conf
systemctl enable nftables >/dev/null 2>&1

# ---------------------------------------------------------------------------------------------------- etcd: join or form
STATE=new
CLUSTER=$(echo "$MEMBERS" | tr ',' '\n' | awk -F= '{printf "%s%s=http://%s:2380", (NR>1?",":""), $1, $2}')
PEER=""
for ip in $OTHERS; do
  if etcdctl --endpoints="http://$ip:2379" --command-timeout=4s endpoint health >/dev/null 2>&1; then PEER=$ip; break; fi
done
if [ -n "$PEER" ]; then
  EP="http://$PEER:2379"
  LISTING=$(etcdctl --endpoints="$EP" member list)
  if echo "$LISTING" | awk -F', ' -v u="http://$MYIP:2380" '$2=="unstarted" && $4==u {f=1} END{exit !f}'; then
    # A brand-new group is still forming and the others already have a majority: this node is in their list but has not started yet.
    # It must NOT be removed and re-added (etcd refuses while the group is not fully up); it just starts with the original list and connects.
    echo "== the group is still forming and already lists this node: starting with the original member list"
  else
    echo "== an etcd cluster is already running (via $PEER): joining it"
    # a lost machine of the same name/address must go first, or `member add` is refused
    echo "$LISTING" | awk -F', ' -v n="$ME" -v u="http://$MYIP:2380" '$3==n || $4==u {print $1}' |
      while read -r id; do echo "removing stale member $id"; etcdctl --endpoints="$EP" member remove "$id"; done
    OUT=""
    for i in $(seq 1 12); do   # etcd refuses a change for a few seconds while the group settles ("unhealthy cluster")
      OUT=$(etcdctl --endpoints="$EP" member add "$ME" --peer-urls="http://$MYIP:2380" 2>&1) && break
      echo "member add not accepted yet: $(echo "$OUT" | tail -1)"; OUT=""; sleep 10
    done
    CLUSTER=$(echo "$OUT" | sed -n 's/^ETCD_INITIAL_CLUSTER="\(.*\)"$/\1/p')
    [ -n "$CLUSTER" ] || { echo "member add never succeeded" >&2; exit 1; }
    STATE=existing
  fi
else
  echo "== no etcd answers: starting as part of a new cluster of $MEMBERS"
fi
cat > /etc/default/etcd <<ETCDENV
# managed by cloud-init (db-ha-node)
ETCD_NAME=$ME
ETCD_DATA_DIR=/var/lib/etcd/db-ha
ETCD_LISTEN_PEER_URLS=http://$MYIP:2380
ETCD_LISTEN_CLIENT_URLS=http://$MYIP:2379,http://127.0.0.1:2379
ETCD_INITIAL_ADVERTISE_PEER_URLS=http://$MYIP:2380
ETCD_ADVERTISE_CLIENT_URLS=http://$MYIP:2379
ETCD_INITIAL_CLUSTER=$CLUSTER
ETCD_INITIAL_CLUSTER_STATE=$STATE
ETCD_INITIAL_CLUSTER_TOKEN=finance-db-ha
ETCD_HEARTBEAT_INTERVAL=250
ETCD_ELECTION_TIMEOUT=2500
ETCD_AUTO_COMPACTION_MODE=periodic
ETCD_AUTO_COMPACTION_RETENTION=1h
ETCD_QUOTA_BACKEND_BYTES=536870912
ETCDENV
systemctl enable etcd >/dev/null 2>&1
systemctl restart etcd
for i in $(seq 1 120); do
  etcdctl --endpoints="http://$MYIP:2379" --command-timeout=4s endpoint health >/dev/null 2>&1 && break
  sleep 5
done
etcdctl --endpoints="http://$MYIP:2379" --command-timeout=4s endpoint health || { echo "etcd did not become healthy on $ME" >&2; exit 1; }
echo "== etcd is healthy ($STATE)"

if [ "$ROLE" = database ]; then
  # ------------------------------------------------------------------------------------------------ Patroni
  CONF=/etc/postgresql/$PGV/main
  DATA=/var/lib/postgresql/$PGV/main
  ETCD_HOSTS=$(echo "$ALL_IPS" | tr ',' '\n' | sed 's/$/:2379/' | paste -sd, -)
  systemctl mask "postgresql@$PGV-main" >/dev/null 2>&1
  [ -f "$CONF/postgresql.base.conf" ] || cp -a "$CONF/postgresql.conf" "$CONF/postgresql.base.conf"
  find "$DATA" -mindepth 1 -delete          # first boot: whatever the package created; Patroni fills it (initdb or copy of the leader)
  HBA_POSTGRES=""
  for ip in $(echo "$MEMBERS" | tr ',' '\n' | grep -v '^db-witness=' | awk -F= '{print $2}'); do
    HBA_POSTGRES="$HBA_POSTGRES
    - host all postgres $ip/32 scram-sha-256"
  done
  CALLBACKS=""
  if [ -n "${NTFY_URL:-}" ]; then
    # a message on the ntfy topic whenever this database changes role (Patroni calls the script)
    umask 077; printf 'NTFY_URL=%s\n' "$NTFY_URL" > /etc/default/patroni-notify; umask 022
    chown postgres:postgres /etc/default/patroni-notify
    cat > /usr/local/bin/patroni-notify <<'NOTIFY'
#!/bin/sh
# Patroni callback: $1 = action, $2 = role, $3 = cluster. Tells the ntfy topic when this node changes role.
[ "$1" = on_role_change ] || exit 0
. /etc/default/patroni-notify 2>/dev/null || exit 0
curl -fsS -m 10 -H "Title: database role change" -H "Priority: high" -H "Tags: twisted_rightwards_arrows" \
  -d "$(hostname) is now $2 (cluster $3)" "$NTFY_URL" >/dev/null 2>&1 &
exit 0
NOTIFY
    chmod 755 /usr/local/bin/patroni-notify
    CALLBACKS="  callbacks:
    on_role_change: /usr/local/bin/patroni-notify"
  fi
  mkdir -p /etc/patroni
  cat > /etc/patroni/config.yml <<YAML
# managed by cloud-init (db-ha-node); docs/db-ha-patroni.md. Holds passwords: root/postgres only.
scope: $SCOPE
namespace: /patroni/
name: $ME
log:
  level: INFO
etcd3:
  hosts: $ETCD_HOSTS
restapi:
  listen: 0.0.0.0:8008
  connect_address: $MYIP:8008
  authentication:
    username: patroni
    password: "$REST_PASSWORD"
bootstrap:
  dcs:
    ttl: 30
    loop_wait: 10
    retry_timeout: 10
    maximum_lag_on_failover: 1048576
    primary_start_timeout: 60
    failsafe_mode: true
    synchronous_mode: false
    postgresql:
      use_pg_rewind: true
      use_slots: true
      parameters:
        wal_level: replica
        hot_standby: "on"
        max_wal_senders: 10
        max_replication_slots: 10
        wal_log_hints: "on"
        hot_standby_feedback: "on"
        max_slot_wal_keep_size: 2GB
  initdb:
    - encoding: UTF8
    - locale: C.UTF-8
postgresql:
  listen: 0.0.0.0:5432
  connect_address: $MYIP:5432
  data_dir: $DATA
  config_dir: $CONF
  custom_conf: $CONF/postgresql.base.conf
  bin_dir: /usr/lib/postgresql/$PGV/bin
  pgpass: /var/lib/postgresql/.pgpass-patroni
  authentication:
    superuser:
      username: postgres
      password: "$PG_PASSWORD"
    replication:
      username: replicator
      password: "$REPL_PASSWORD"
  parameters:
    unix_socket_directories: /var/run/postgresql
$CALLBACKS
  pg_hba:
    - local all postgres peer
    - local all all peer
    - host all all 127.0.0.1/32 scram-sha-256
    - host all all ::1/128 scram-sha-256
    - local replication all peer
    - host replication all 127.0.0.1/32 scram-sha-256
    - host replication all ::1/128 scram-sha-256
    - host financedb financeapp 192.168.0.0/16 scram-sha-256
    - host financedb financeapp 10.0.0.0/16 scram-sha-256
    - host replication replicator 10.0.1.0/24 scram-sha-256
    - host postgres monitor 10.0.1.0/24 scram-sha-256$HBA_POSTGRES
tags:
  nofailover: false
  noloadbalance: false
  clonefrom: false
  nosync: false
YAML
  chown postgres:postgres /etc/patroni/config.yml; chmod 600 /etc/patroni/config.yml
  # `patronictl` with no arguments just works for root
  grep -q PATRONICTL_CONFIG_FILE /etc/environment || echo 'PATRONICTL_CONFIG_FILE=/etc/patroni/config.yml' >> /etc/environment
  mkdir -p /root/.config/patroni && ln -sf /etc/patroni/config.yml /root/.config/patroni/patronictl.yaml
  systemctl enable patroni >/dev/null 2>&1
  systemctl restart patroni
  echo "== Patroni started; waiting for this node to be Leader or a streaming Replica"
  for i in $(seq 1 180); do
    ST=$(curl -fsS -m 4 "http://127.0.0.1:8008/patroni" 2>/dev/null | jq -r '.role + ":" + .state' 2>/dev/null || true)
    case "$ST" in master:running|primary:running|replica:running|standby_leader:running) break ;; esac
    sleep 5
  done
  echo "== Patroni: ${ST:-no answer}"
fi

touch /var/lib/db-ha-node.done
echo "== done $(date -Is)"
